const LEVEL_LABEL = { 3: '높음', 2: '보통', 1: '낮음' };

function inferDemand(ev) {
  const text = `${ev.title || ''} ${ev.addr || ''}`;
  const hit = RULES.find(r => r.kw.test(text)) || DEFAULT;
  const seed = seedOf(ev.ext_id || ev.title);
  const cuts = pick(hit.pool, seed, 3);           // 행사마다 다른 3부위
  const reason = hit.reasons[seed % hit.reasons.length];
  return {
    category: hit.cat,
    species: hit.species,
    cuts,                                          // ['삼겹살','항정살','닭꼬치']
    cut: cuts.join(' · '),
    level: hit.level,
    level_label: LEVEL_LABEL[hit.level] || '보통',
    suggest_qty: hit.qty,
    reason
  };
}

