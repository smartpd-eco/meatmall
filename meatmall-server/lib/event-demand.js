// 문자열 → 안정적 해시(행사별 추천 다양화 시드)
function seedOf(s) {
  s = String(s || '');
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}
// 풀에서 시드 기반으로 겹치지 않게 n개 선택
function pick(pool, seed, n) {
  const arr = pool.slice(), out = [];
  for (let i = 0; i < n && arr.length; i++) {
    const idx = (seed + i * 7) % arr.length;
    out.push(arr.splice(idx, 1)[0]);
  }
  return out;
}

